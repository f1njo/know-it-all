def bank_questions(subject, difficulty, rng):
    result = []
    for index, row in enumerate(BANK[(subject, difficulty)].strip().splitlines()):
        prompt, answer, wrong, explanation = row.split('|')
        options = [answer, *wrong.split('/')]
        rng.shuffle(options)
        # Short English vocabulary and numeric logic also train keyboard input.
        typed = ((subject == 'Английский' and ' ' not in answer and index % 3 == 0)
                 or (subject == 'Информатика' and answer.isdigit()))
        result.append(Question(prompt, answer, tuple(options), explanation, typed))
    rng.shuffle(result)
    return result


def math_questions(difficulty, rng):
    result = []
    seen = set()
    while len(result) < 10:
        level = DIFFICULTIES.index(difficulty)
        kind = rng.choice(('sum', 'difference', 'missing', 'story') if level == 0
                          else ('sum', 'difference', 'product', 'division', 'missing', 'story', 'two_steps'))
        limit = (10, 50, 100)[level]
        a, b = rng.randint(1, limit), rng.randint(1, limit)
        if kind == 'sum':
            answer = a + b
            prompt = f'{a} + {b} = ?'
            explanation = f'Складываем {a} и {b}: {answer}.'
        elif kind == 'difference':
            a, b = max(a, b), min(a, b)
            answer = a - b
            prompt = f'{a} − {b} = ?'
            explanation = f'Вычитаем {b} из {a}: {answer}.'
        elif kind == 'missing':
            answer = b
            prompt = f'{a} + □ = {a + b}. Какое число скрыто?'
            explanation = f'Из суммы вычитаем известное число: {a + b} − {a} = {b}.'
        elif kind in ('product', 'division'):
            a, b = rng.randint(2, 5 if level == 1 else 10), rng.randint(2, 10)
            if kind == 'product':
                answer, prompt = a * b, f'{a} × {b} = ?'
                explanation = f'{a} групп по {b}: {a} × {b} = {answer}.'
            else:
                answer, prompt = b, f'{a * b} ÷ {a} = ?'
                explanation = f'{a} × {b} = {a * b}, поэтому {a * b} ÷ {a} = {b}.'
        elif kind == 'two_steps':
            c = rng.randint(1, a + b)
            answer, prompt = a + b - c, f'({a} + {b}) − {c} = ?'
            explanation = f'Сначала считаем в скобках: {a + b}. Затем {a + b} − {c} = {answer}.'
        else:
            answer = a + b
            prompt = f'У Миши {a} наклеек. Ему подарили ещё {b}. Сколько наклеек стало?'
            explanation = f'Наклеек стало больше: {a} + {b} = {answer}.'
        if prompt in seen:
            continue
        seen.add(prompt)
        distractors = set()
        while len(distractors) < 3:
            wrong = answer + rng.choice((-5, -3, -2, -1, 1, 2, 3, 5))
            if wrong >= 0 and wrong != answer:
                distractors.add(wrong)
        options = [str(answer), *(str(x) for x in sorted(distractors))]
        rng.shuffle(options)
        result.append(Question(prompt, str(answer), tuple(options), explanation, len(result) % 3 == 2))
    return result


def make_test(subject, difficulty, rng=None):
    if subject not in SUBJECTS or difficulty not in DIFFICULTIES:
        raise ValueError('Неизвестный предмет или уровень сложности')
    rng = rng or random.Random()
    return (math_questions(difficulty, rng) if subject == 'Математика'
            else bank_questions(subject, difficulty, rng))


