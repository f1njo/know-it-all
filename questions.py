    def __init__(self, questions):
        if not questions:
            raise ValueError('Тест не может быть пустым')
        self.questions = questions
        self.index = 0
        self.score = self.correct = self.streak = self.best_streak = 0
        self.answered = False
        self.history = []

    @property
    def current(self):
        return self.questions[self.index]

    def submit(self, answer):
        if self.answered:
            return None
        right = normalize(answer) == normalize(self.current.answer)
        if right:
            self.score += 10 + 2 * self.streak
            self.correct += 1
            self.streak += 1
            self.best_streak = max(self.best_streak, self.streak)
        else:
            self.streak = 0
        self.answered = True
        self.history.append((self.current, str(answer).strip(), right))
        return right

    def advance(self):
        if not self.answered:
            return False
        if self.index + 1 == len(self.questions):
            return False
        self.index += 1
        self.answered = False
        return True
